def total(name: str) -> str:
    """Рядок «Підсумок: N з M перевірок пройдено» зі збереженого виводу."""
    line = next(l for l in (OUT / name).read_text().splitlines() if l.startswith("Підсумок: ") and "перевір" in l)
    return re.search(r"(\d+ з \d+)", line).group(1)


